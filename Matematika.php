<?php

class Matematika

{
    public static $pi = 3.14;

    public static function сложить($a, $b) {        return $a + $b;
    }


    public static function вычесть($a, $b) {
        return $a - $b;
    }

    public static function умножить($a, $b) {
        return $a * $b;
    }
    public static function разделить($a, $b) {

        return $a / $b;
    }
}